def generate_order_id(prefix: str = "ORD") -> str:
    global _order_counter
    _order_counter += 1
    return f"{prefix}{datetime.now().strftime('%Y%m%d')}{_order_counter}"


def save_order(order_id: str, order_info: dict):
    _orders[order_id] = {
        **order_info,
        "created_at": datetime.now().isoformat(),
        "status": "confirmed",
    }
    _flush_orders()


def get_order(order_id: str) -> dict | None:
    return _orders.get(order_id)


def list_orders() -> list[dict]:
    return sorted(_orders.values(), key=lambda o: o.get("created_at", ""), reverse=True)
